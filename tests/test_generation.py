def _groups(config: dict) -> dict[str, dict]:
    return {item["name"]: item for item in config["proxy-groups"]}


def _provider_servers(config: dict, prefix: str) -> set[str]:
    servers: set[str] = set()
    for name, provider in config["proxy-providers"].items():
        if name.startswith(prefix):
            servers.update(item["server"] for item in provider["payload"])
    return servers


def _build(paths: dict[str, Path], env: dict[str, str]):  # noqa: ANN202
    return build_candidate(**paths, env=env)



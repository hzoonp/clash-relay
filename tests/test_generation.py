def test_rules_refer_only_to_public_groups_or_builtins(built_candidate) -> None:
    config = built_candidate.config
    public = {group["name"] for group in config["proxy-groups"] if not group.get("hidden", False)}
    builtins = {"DIRECT", "REJECT", "PASS", "COMPATIBLE"}
    for rule in config["rules"]:
        parts = rule.split(",")
        target = parts[1] if parts[0] == "MATCH" else parts[2]
        assert target in public | builtins


def test_output_round_trip_is_stable(built_candidate) -> None:
    loaded = yaml.safe_load(built_candidate.yaml_text)
    assert dump_yaml(loaded, header=True) == built_candidate.yaml_text
